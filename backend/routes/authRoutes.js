// =========================================================
// SecurePass - Authentication Routes
// =========================================================

const express = require("express");

const router = express.Router();


// =========================================================
// Controllers
// =========================================================

const {
    registerUser,
    loginUser,
    logoutUser
} = require("../controllers/authController");


// =========================================================
// Middleware
// =========================================================

const authMiddleware =
    require("../middleware/authMiddleware");


// =========================================================
// Register
// =========================================================

router.post(
    "/register",
    registerUser
);


// =========================================================
// Login
// =========================================================

router.post(
    "/login",
    loginUser
);


// =========================================================
// Logout
// =========================================================

router.post(
    "/logout",
    authMiddleware,
    logoutUser
);


// =========================================================
// Export
// =========================================================

module.exports = router;